/**
 * Automated Data Validation Check
 * Enforces strict integrity rules specified in frontend recovery.
 */
export function validateMenuData() {
  const errors = [];
  const idSet = new Set();

  MENU_ITEMS.forEach((item, index) => {
    // 1. Name check
    if (!item.name || typeof item.name !== 'string' || item.name.trim() === '') {
      errors.push(`Item at index ${index} is missing a valid name.`);
    }

    // 2. Category check
    if (!item.category || typeof item.category !== 'string') {
      errors.push(`Item ${item.name || index} is missing a valid category.`);
    } else {
      const categoryExists = MENU_CATEGORIES.some((c) => c.id === item.category);
      if (!categoryExists) {
        errors.push(`Item ${item.name} references non-existent category "${item.category}".`);
      }
    }

    // 3. Price check
    if (typeof item.price !== 'number' || isNaN(item.price)) {
      errors.push(`Item ${item.name} has an invalid price: ${item.price}`);
    } else if (item.price < 0) {
      errors.push(`Item ${item.name} has a negative price: ₹${item.price}`);
    }

    // 4. Image check
    if (!('image' in item)) {
      errors.push(`Item ${item.name} is missing the explicit "image" property.`);
    }

    // 5. Stable unique ID check
    if (!item.id || typeof item.id !== 'string') {
      errors.push(`Item ${item.name || index} is missing a valid stable ID.`);
    } else if (idSet.has(item.id)) {
      errors.push(`Duplicate ID detected: "${item.id}" on item ${item.name}`);
    } else {
      idSet.add(item.id);
    }
  });

  return {
    isValid: errors.length === 0,
    totalItems: MENU_ITEMS.length,
    totalCategories: MENU_CATEGORIES.length,
    verifiedCategoriesCount: MENU_CATEGORIES.filter((c) => c.status === 'VERIFIED').length,
    pendingVerificationCategoriesCount: MENU_CATEGORIES.filter((c) => c.status !== 'VERIFIED').length,
    errors,
  };
}
